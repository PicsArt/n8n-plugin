"""Vendor only endpoint-compatible choices; preserve existing workflow IDs/defaults."""
import json, pathlib, hashlib, sys
source = pathlib.Path(sys.argv[1] if len(sys.argv)>1 else '../shared-models/catalog.json')
root = pathlib.Path(__file__).resolve().parents[1]
catalog = json.loads(source.read_text())
ids = ['genai-text2image','genai-text2sticker','genai-text2speech','genai-text2sound']
selected = {o['id']:o['model_ids'] for o in catalog['operations'] if o['id'] in ids}
assert len(selected)==4
for operation in catalog['operations']:
 if operation['id'] in ids:
  assert operation['content_type'] == 'application/json'
  assert operation['path'] == '/' + operation['id'].removeprefix('genai-')
  assert any(server['url'] == 'https://genai-api.picsart.io/v1' for server in operation['servers'])
  assert operation['model_field'] == 'model'

out = '// Generated by scripts/sync-model-catalog.py; do not edit model IDs by hand.\n'
out += '// Captured '+catalog['observed_date']+'; catalog SHA256 '+hashlib.sha256(source.read_bytes()).hexdigest()+'\n'
out += "import type { INodePropertyOptions } from 'n8n-workflow';\n\n"
out += 'export const capturedModelIds: Record<string, string[]> = '+json.dumps(selected,indent=2)+';\n\n'
out += '''/** Keep legacy IDs until retirement is confirmed; never convert provider aliases. */
export function modelOptions(operation: string, legacy: INodePropertyOptions[]): INodePropertyOptions[] {
 const ids = capturedModelIds[operation];
 if (!ids) throw new Error('No compatible model catalog for operation: ' + operation);
 const options = new Map(legacy.map(option => [option.value, option]));
 for (const id of ids) if (!options.has(id)) options.set(id, { name: id, value: id });
 return [...options.values()].sort((a, b) => a.name.localeCompare(b.name));
}
'''
(root/'nodes/PicsartGeneration/modelOptions.ts').write_text(out)
